#!/usr/bin/env bash
# Builds AeroSpace.app and the aerospace CLI from this checkout with just the Xcode command line tools (no Xcode),
# which the upstream release build (build-release.sh) needs. It uses SwiftPM, which can build the app's executable,
# and puts the bundle together by hand: Info.plist, icon, default config, code signature.
#
#   ./build-local-app.sh                      build into .release/
#   ./build-local-app.sh --install            also replace /Applications/AeroSpace.app and the CLI, and restart it
#   ./build-local-app.sh --codesign-identity NAME
#                                             sign with this identity (default: aerospace-local-codesign, made by
#                                             script/create-local-codesign-cert.sh; ad hoc if there is none)
set -euo pipefail
cd "$(dirname "$0")"

identity="aerospace-local-codesign"
install=0
while test $# -gt 0; do
    case $1 in
        --install) install=1; shift ;;
        --codesign-identity) identity="$2"; shift 2 ;;
        *) echo "Unknown option $1" >&2; exit 1 ;;
    esac
done

version="$(git describe --tags --always --dirty 2>/dev/null | sed 's/^v//' || true)"
version="${version:-0.0.0-SNAPSHOT}"

# What the app and the CLI report as their version (the same files generate.sh writes)
restore() { git checkout -q -- Sources/Common/versionGenerated.swift Sources/Common/gitHashGenerated.swift 2>/dev/null || true; }
trap restore EXIT
cat >Sources/Common/versionGenerated.swift <<GEN
// FILE IS GENERATED BY generate.sh
public let aeroSpaceAppVersion = "$version"
GEN
cat >Sources/Common/gitHashGenerated.swift <<GEN
// FILE IS GENERATED BY generate.sh
public let gitHash = "$(git rev-parse HEAD)"
public let gitShortHash = "$(git rev-parse --short HEAD)"
GEN

# The version is a constant that SwiftPM inlines into the other modules and does not always notice changing,
# which leaves the app and the CLI reporting different versions. A full rebuild takes a few minutes, once per new version.
stamp=.build/.local-app-version
if [[ "$(cat "$stamp" 2>/dev/null)" != "$version" ]]; then
    rm -rf .build/*/release
fi
swift build -c release --product AeroSpaceApp --product aerospace
mkdir -p .build && echo "$version" >"$stamp"
bin="$(swift build -c release --show-bin-path)"

out=.release
app="$out/AeroSpace.app"
rm -rf "$out" && mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$bin/AeroSpaceApp" "$app/Contents/MacOS/AeroSpace"
cp "$bin/aerospace" "$out/aerospace"
cp docs/config-examples/default-config.toml "$app/Contents/Resources/"

# The icon: the asset catalog needs Xcode's compiler, so make an .icns from the 1024px picture instead
iconset="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$iconset"
src=resources/Assets.xcassets/AppIcon.appiconset/icon.png
for size in 16 32 128 256 512; do
    sips -z $size $size "$src" --out "$iconset/icon_${size}x${size}.png" >/dev/null
    sips -z $((size * 2)) $((size * 2)) "$src" --out "$iconset/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$iconset" -o "$app/Contents/Resources/AppIcon.icns"

cat >"$app/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleExecutable</key><string>AeroSpace</string>
	<key>CFBundleIconFile</key><string>AppIcon</string>
	<key>CFBundleIdentifier</key><string>bobko.aerospace</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>AeroSpace</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>$version</string>
	<key>CFBundleVersion</key><string>1</string>
	<key>LSMinimumSystemVersion</key><string>13.0</string>
	<key>LSUIElement</key><true/>
</dict>
</plist>
PLIST
printf 'APPL????' >"$app/Contents/PkgInfo"

if security find-certificate -c "$identity" >/dev/null 2>&1; then
    sign=("$identity")
else
    echo "No signing certificate '$identity' (script/create-local-codesign-cert.sh makes one): signing ad hoc," \
        "so macOS will ask for the Accessibility permission again after every rebuild" >&2
    sign=("-")
fi
codesign --force --sign "${sign[0]}" --entitlements resources/AeroSpace.entitlements "$app"
codesign --force --sign "${sign[0]}" "$out/aerospace"
codesign --verify --strict "$app" && echo "Built $app ($version), signed with ${sign[0]}"

if test $install = 1; then
    cli_dir="$(command -v brew >/dev/null && echo "$(brew --prefix)/bin" || echo /usr/local/bin)"
    if command -v brew >/dev/null && brew list --cask aerospace >/dev/null 2>&1; then
        brew uninstall --cask aerospace # removes the released app and CLI; the config stays
    fi
    osascript -e 'tell application "AeroSpace" to quit' >/dev/null 2>&1 || true
    sleep 1
    rm -rf /Applications/AeroSpace.app
    ditto "$app" /Applications/AeroSpace.app
    install -m 755 "$out/aerospace" "$cli_dir/aerospace"
    open /Applications/AeroSpace.app
    echo "Installed. If windows are not being managed, grant AeroSpace the Accessibility permission" \
        "(System Settings > Privacy & Security > Accessibility), toggling it off and on if it is already listed."
fi
